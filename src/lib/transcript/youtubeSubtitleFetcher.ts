import type { SentenceSegment } from '../../types/index.ts'
import {
  cleanTranscriptText,
  parseSrtOrVtt,
} from './transcriptParser.ts'

const VIDEO_ID_REGEX = /^[a-zA-Z0-9_\-]{10,12}$/

interface YouTubeCaptionTrack {
  baseUrl: string
  name?: { runs?: Array<{ text?: string }> }
  vssId?: string
  languageCode: string
  kind?: string
  isTranslatable?: boolean
}

interface YouTubePlayerResponse {
  videoDetails?: {
    videoId?: string
    title?: string
    author?: string
    lengthSeconds?: string
  }
  captions?: {
    playerCaptionsTracklistRenderer?: {
      captionTracks?: YouTubeCaptionTrack[]
    }
  }
}

/**
 * Parses SRV3 / timedtext XML into clean sentence segments
 */
export function parseTimedTextXml(xml: string): SentenceSegment[] {
  const pRegex = /<p t="(\d+)"(?: d="(\d+)")?[^>]*>(.*?)<\/p>/gs
  const rawSegments: Array<{ startTime: number; endTime: number; text: string }> = []
  let match: RegExpExecArray | null

  while ((match = pRegex.exec(xml)) !== null) {
    const startMs = parseInt(match[1], 10)
    const durMs = match[2] ? parseInt(match[2], 10) : 3000

    const rawText = cleanTranscriptText(match[3])
    if (
      rawText &&
      !/^(\[|\()(music|applause|laughter|cheering|chuckle|giggle|sound)(\]|\))$/i.test(rawText) &&
      rawText.length > 1
    ) {
      const startTime = Math.round((startMs / 1000) * 10) / 10
      const endTime = Math.round(((startMs + durMs) / 1000) * 10) / 10

      rawSegments.push({
        startTime,
        endTime: endTime > startTime ? endTime : Math.round((startTime + 3.0) * 10) / 10,
        text: rawText,
      })
    }
  }

  // Merge micro-segments (e.g. < 4 words or < 2.5s without terminal punctuation)
  const merged: SentenceSegment[] = []
  let buffer: { startTime: number; endTime: number; text: string } | null = null

  for (let i = 0; i < rawSegments.length; i++) {
    const cur = rawSegments[i]
    if (!buffer) {
      buffer = { ...cur }
      continue
    }

    const wordCount = buffer.text.split(/\s+/).length
    const duration = buffer.endTime - buffer.startTime
    const hasTerminalPunctuation = /[.!?]$/.test(buffer.text.trim())

    if ((wordCount < 4 || duration < 2.5) && !hasTerminalPunctuation && buffer.text.length < 80) {
      buffer.text = `${buffer.text} ${cur.text}`
      buffer.endTime = cur.endTime
    } else {
      merged.push({
        id: `seg-${merged.length + 1}`,
        startTime: buffer.startTime,
        endTime: buffer.endTime,
        text: buffer.text,
      })
      buffer = { ...cur }
    }
  }

  if (buffer) {
    merged.push({
      id: `seg-${merged.length + 1}`,
      startTime: buffer.startTime,
      endTime: buffer.endTime,
      text: buffer.text,
    })
  }

  return merged
}

/**
 * Core YouTube InnerTube subtitle fetcher
 */
export async function fetchYouTubeSubtitles(
  videoId: string,
  preferredLang = 'en'
): Promise<{
  success: boolean
  title?: string
  author?: string
  language?: string
  isAutoGenerated?: boolean
  sentences?: SentenceSegment[]
  error?: string
}> {
  if (!VIDEO_ID_REGEX.test(videoId)) {
    return { success: false, error: 'Định dạng YouTube Video ID không hợp lệ.' }
  }

  try {
    const resp = await fetch('https://www.youtube.com/youtubei/v1/player?prettyPrint=false', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'User-Agent': 'com.google.android.youtube/20.10.38 (Linux; U; Android 14)',
      },
      body: JSON.stringify({
        context: {
          client: {
            clientName: 'ANDROID',
            clientVersion: '20.10.38',
          },
        },
        videoId,
      }),
    })

    if (!resp.ok) {
      return {
        success: false,
        error:
          resp.status === 429
            ? 'YouTube đang tạm thời giới hạn tải phụ đề tự động (HTTP 429). Bạn có thể bấm "Dán phụ đề nhanh" để nạp transcript từ YouTube trong 5 giây.'
            : `YouTube API phản hồi mã lỗi ${resp.status}`,
      }
    }

    const data = (await resp.json()) as YouTubePlayerResponse
    const title = data.videoDetails?.title
    const author = data.videoDetails?.author
    const tracks = data.captions?.playerCaptionsTracklistRenderer?.captionTracks

    if (!Array.isArray(tracks) || tracks.length === 0) {
      return {
        success: false,
        title,
        error: 'Video này không có sẵn phụ đề (captions) trên YouTube.',
      }
    }

    // Prioritize human English, then auto English, then any track
    const humanEnTrack = tracks.find(
      (t) =>
        (t.languageCode === preferredLang || t.languageCode.startsWith(preferredLang)) &&
        !t.vssId?.startsWith('a.')
    )
    const autoEnTrack = tracks.find(
      (t) => t.languageCode === preferredLang || t.languageCode.startsWith(preferredLang)
    )
    const selectedTrack = humanEnTrack || autoEnTrack || tracks[0]

    const isAuto = selectedTrack.vssId?.startsWith('a.') || selectedTrack.kind === 'asr'
    let segments: SentenceSegment[] = []

    if (!isAuto) {
      try {
        const vttUrl = selectedTrack.baseUrl.includes('fmt=')
          ? selectedTrack.baseUrl.replace(/fmt=[^&]+/, 'fmt=vtt')
          : `${selectedTrack.baseUrl}&fmt=vtt`

        const vttResp = await fetch(vttUrl)
        if (vttResp.ok) {
          const vttText = await vttResp.text()
          segments = parseSrtOrVtt(vttText)
        }
      } catch (err) {
        console.warn('[YouTube Subtitles] Failed to fetch VTT, falling back to XML', err)
      }
    }

    if (segments.length === 0) {
      const xmlResp = await fetch(selectedTrack.baseUrl)
      if (!xmlResp.ok) {
        return {
          success: false,
          title,
          error:
            xmlResp.status === 429
              ? 'YouTube đang tạm thời giới hạn tải phụ đề tự động (HTTP 429). Bạn có thể bấm "Dán phụ đề nhanh" để nạp transcript từ YouTube trong 5 giây.'
              : `Không thể tải nội dung phụ đề từ YouTube (HTTP ${xmlResp.status}).`,
        }
      }
      const xmlText = await xmlResp.text()
      segments = parseTimedTextXml(xmlText)
    }

    if (segments.length === 0) {
      return {
        success: false,
        title,
        error: 'Không tìm thấy nội dung câu phụ đề nào trong video.',
      }
    }

    return {
      success: true,
      title,
      author,
      language: selectedTrack.languageCode,
      isAutoGenerated: isAuto,
      sentences: segments,
    }
  } catch (err) {
    return {
      success: false,
      error: err instanceof Error ? err.message : 'Lỗi không xác định khi tải phụ đề YouTube.',
    }
  }
}
