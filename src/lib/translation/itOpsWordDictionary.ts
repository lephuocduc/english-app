/**
 * Look up a single English word (or common inflected form) in our contextual IT Ops dictionary.
 * Returns formatted "(pos) Vietnamese meaning" or null if not found.
 */
export function lookupContextualWord(rawWord: string): string | null {
  const cleaned = rawWord
    .trim()
    .toLowerCase()
    .replace(/^[^\w'-]+|[^\w'-]+$/g, '')
    .replace(/['’]s$/, '')
  if (!cleaned) return null

  if (IT_OPS_WORD_DICTIONARY[cleaned]) {
    return IT_OPS_WORD_DICTIONARY[cleaned]
  }

  // Fallback stem matching for regular inflections
  if (cleaned.endsWith('ies') && cleaned.length > 4) {
    const base = `${cleaned.slice(0, -3)}y`
    if (IT_OPS_WORD_DICTIONARY[base]) return IT_OPS_WORD_DICTIONARY[base]
  }
  if (cleaned.endsWith('es') && cleaned.length > 3) {
    const base = cleaned.slice(0, -2)
    if (IT_OPS_WORD_DICTIONARY[base]) return IT_OPS_WORD_DICTIONARY[base]
  }
  if (cleaned.endsWith('s') && cleaned.length > 3) {
    const base = cleaned.slice(0, -1)
    if (IT_OPS_WORD_DICTIONARY[base]) return IT_OPS_WORD_DICTIONARY[base]
  }
  if (cleaned.endsWith('ed') && cleaned.length > 4) {
    const base1 = cleaned.slice(0, -2)
    const base2 = cleaned.slice(0, -1)
    if (IT_OPS_WORD_DICTIONARY[base1]) return IT_OPS_WORD_DICTIONARY[base1]
    if (IT_OPS_WORD_DICTIONARY[base2]) return IT_OPS_WORD_DICTIONARY[base2]
  }
  if (cleaned.endsWith('ing') && cleaned.length > 5) {
    const base1 = cleaned.slice(0, -3)
    const base2 = `${cleaned.slice(0, -3)}e`
    if (IT_OPS_WORD_DICTIONARY[base1]) return IT_OPS_WORD_DICTIONARY[base1]
    if (IT_OPS_WORD_DICTIONARY[base2]) return IT_OPS_WORD_DICTIONARY[base2]
  }

  return null
}
