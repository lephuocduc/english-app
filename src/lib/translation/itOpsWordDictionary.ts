/**
 * Parse a meaning string formatted like "(n) bộ nhớ, RAM" into { pos, text }.
 */
export function parseMeaningWithPos(rawMeaning?: string): { pos: string | null; text: string } {
  const trimmed = (rawMeaning || '').trim()
  if (!trimmed) return { pos: null, text: '' }
  const match = trimmed.match(/^\(([a-z/]+)\)\s*(.+)$/i)
  if (!match) return { pos: null, text: trimmed }
  return {
    pos: match[1].toLowerCase(),
    text: match[2].trim(),
  }
}

/**
 * Combine a part-of-speech code and meaning text into "(pos) text".
 */
export function formatMeaningWithPos(pos: string, meaningText: string): string {
  const cleanText = meaningText.trim()
  const cleanPos = pos.trim().toLowerCase()
  if (!cleanText) return cleanPos ? `(${cleanPos})` : ''
  if (!cleanPos) return cleanText
  // Avoid double prefix if already prefixed
  if (/^\([a-z/]+\)\s*/i.test(cleanText)) return cleanText
  return `(${cleanPos}) ${cleanText}`
}

