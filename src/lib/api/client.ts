import type {
  Lesson,
  SentenceSegment,
  UserLessonProgress,
  VocabularyItem,
} from '../../types'

const USER_ID_KEY = 'listenflow_user_id_v1'

/**
 * Returns or generates a stable anonymous or authenticated user ID
 */
export function getStoredUserId(): string {
  if (typeof window === 'undefined') return 'leducst1'
  try {
    let id = window.localStorage.getItem(USER_ID_KEY)
    if (!id) {
      id = 'leducst1'
      window.localStorage.setItem(USER_ID_KEY, id)
    }
    return id
  } catch {
    return 'leducst1'
  }
}

export function setStoredUserId(newId: string): void {
  if (typeof window === 'undefined') return
  try {
    const trimmed = newId.trim()
    if (trimmed) {
      window.localStorage.setItem(USER_ID_KEY, trimmed)
    }
  } catch {
    // ignore
  }
}

export const CLOUDFLARE_WORKER_DEFAULT_API = 'https://listenflow-api.duc-todo-api.workers.dev/api'

export class ApiClient {
  private baseUrl: string
  private apiKey?: string

  constructor(baseUrl?: string, apiKey?: string) {
    const customUrl =
      typeof window !== 'undefined'
        ? window.localStorage.getItem('listenflow_api_base_url')
        : null
    this.baseUrl =
      baseUrl ||
      customUrl ||
      (typeof import.meta !== 'undefined' && import.meta.env?.VITE_API_BASE_URL) ||
      CLOUDFLARE_WORKER_DEFAULT_API
    this.apiKey = apiKey
  }

  private async request<T>(
    endpoint: string,
    options: RequestInit = {}
  ): Promise<{ success: boolean; data?: T; error?: string }> {
    const userId = getStoredUserId()
    const headers: Record<string, string> = {
      'Content-Type': 'application/json',
      'X-User-Id': userId,
      ...(this.apiKey ? { 'X-Api-Key': this.apiKey } : {}),
      ...(options.headers as Record<string, string> || {}),
    }

    try {
      const url = `${this.baseUrl}${endpoint.startsWith('/') ? endpoint : `/${endpoint}`}`
      const res = await fetch(url, {
        ...options,
        headers,
      })

      const json = await res.json() as { success: boolean; data?: T; error?: string }
      return json
    } catch (err) {
      return {
        success: false,
        error: err instanceof Error ? err.message : 'Network request failed',
      }
    }
  }

  async checkHealth() {
    return this.request<{ status: string; database: string }>('/health')
  }

  // --- YouTube Transcript Auto-fetch Endpoint ---
  async fetchYouTubeTranscript(videoId: string, lang = 'en'): Promise<{
    success: boolean
    sentences?: SentenceSegment[]
    title?: string
    author?: string
    language?: string
    isAutoGenerated?: boolean
    error?: string
  }> {
    try {
      const url = `${this.baseUrl}/transcript/${encodeURIComponent(videoId)}?lang=${encodeURIComponent(lang)}`
      const res = await fetch(url, {
        headers: {
          'Content-Type': 'application/json',
          'X-User-Id': getStoredUserId(),
          ...(this.apiKey ? { 'X-Api-Key': this.apiKey } : {}),
        },
      })
      const data = await res.json()
      return data
    } catch (err) {
      return {
        success: false,
        error: err instanceof Error ? err.message : 'Không thể kết nối đến máy chủ lấy phụ đề',
      }
    }
  }

  // --- Lessons Endpoints ---
  async listLessons(): Promise<Lesson[]> {
    const res = await this.request<Lesson[]>('/lessons')
    return res.success && res.data ? res.data : []
  }

  async getLesson(id: string): Promise<Lesson | null> {
    const res = await this.request<Lesson>(`/lessons/${id}`)
    return res.success && res.data ? res.data : null
  }

  async createLesson(lesson: {
    id?: string
    videoId: string
    title: string
    description?: string
    language?: string
    level?: string
    sentences?: SentenceSegment[]
  }): Promise<{ id: string } | null> {
    const res = await this.request<{ id: string }>('/lessons', {
      method: 'POST',
      body: JSON.stringify(lesson),
    })
    return res.success && res.data ? res.data : null
  }

  async updateLesson(
    id: string,
    updates: { title?: string; description?: string; level?: string; language?: string }
  ): Promise<boolean> {
    const res = await this.request(`/lessons/${id}`, {
      method: 'PUT',
      body: JSON.stringify(updates),
    })
    return res.success
  }

  async deleteLesson(id: string): Promise<boolean> {
    const res = await this.request(`/lessons/${id}`, {
      method: 'DELETE',
    })
    return res.success
  }

  // --- Transcript Segments Endpoints ---
  async listSegments(lessonId: string): Promise<SentenceSegment[]> {
    const res = await this.request<SentenceSegment[]>(`/segments/lessons/${lessonId}`)
    return res.success && res.data ? res.data : []
  }

  async addSegments(lessonId: string, segments: SentenceSegment[]): Promise<boolean> {
    const res = await this.request(`/segments/lessons/${lessonId}`, {
      method: 'POST',
      body: JSON.stringify({ segments }),
    })
    return res.success
  }

  async updateSegment(id: string, updates: Partial<SentenceSegment>): Promise<boolean> {
    const res = await this.request(`/segments/${id}`, {
      method: 'PUT',
      body: JSON.stringify(updates),
    })
    return res.success
  }

  async deleteSegment(id: string): Promise<boolean> {
    const res = await this.request(`/segments/${id}`, {
      method: 'DELETE',
    })
    return res.success
  }

  // --- Dictation Attempts Endpoints ---
  async recordAttempt(attempt: {
    lessonId: string
    segmentId: string
    userInput: string
    score: number
    accuracy: number
    correctCount?: number
    missingCount?: number
    incorrectCount?: number
    extraCount?: number
  }): Promise<boolean> {
    const res = await this.request('/attempts', {
      method: 'POST',
      body: JSON.stringify(attempt),
    })
    return res.success
  }

  // --- Per-sentence Learning Progress Endpoints ---
  async getLessonProgress(lessonId: string): Promise<UserLessonProgress | null> {
    const res = await this.request<UserLessonProgress>(`/progress/lessons/${lessonId}`)
    return res.success && res.data ? res.data : null
  }

  async saveSentenceProgress(
    lessonId: string,
    segmentId: string,
    progress: {
      userInput: string
      score: number
      isRevealed: boolean
      completed: boolean
      attemptsCount?: number
    }
  ): Promise<boolean> {
    const res = await this.request(`/progress/lessons/${lessonId}/${segmentId}`, {
      method: 'PUT',
      body: JSON.stringify(progress),
    })
    return res.success
  }

  async resetLessonProgress(lessonId: string): Promise<boolean> {
    const res = await this.request(`/progress/lessons/${lessonId}`, {
      method: 'DELETE',
    })
    return res.success
  }

  // --- Vocabulary Endpoints ---
  async listVocabulary(): Promise<VocabularyItem[]> {
    const res = await this.request<VocabularyItem[]>('/vocabulary')
    return res.success && res.data ? res.data : []
  }

  async saveVocabulary(item: {
    id?: string
    word: string
    meaning?: string
    contextSentence?: string
    timestamp?: number
    videoId?: string
    lessonTitle?: string
  }): Promise<boolean> {
    const res = await this.request('/vocabulary', {
      method: 'POST',
      body: JSON.stringify(item),
    })
    return res.success
  }

  async deleteVocabulary(id: string): Promise<boolean> {
    const res = await this.request(`/vocabulary/${id}`, {
      method: 'DELETE',
    })
    return res.success
  }
}

export const apiClient = new ApiClient()
